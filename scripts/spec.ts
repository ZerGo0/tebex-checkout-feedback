import { ZodError } from 'zod';
import { createBasket, getBasketById } from '../generated/client';
import { finding, headers, newBasket, tebex, usage } from './lib/tebex';

const [paidBasketIdent, refundedTransactionId] = process.argv.slice(2);
if (!paidBasketIdent) {
  usage('Usage: pnpm spec <ident of a paid basket> [<tbx- ID of a refunded payment>]');
}

async function validationIssues(request: () => Promise<unknown>) {
  try {
    await request();
    return ['passes validation'];
  } catch (error) {
    if (!(error instanceof ZodError)) throw error;
    return error.issues.map((issue) => `${issue.path.join('.')}: ${issue.message}`);
  }
}

console.log('Calls Tebex through a client generated by Orval from checkout-api.yaml v1.1.5, with response validation on.');

finding(
  'Creating a basket fails validation',
  'the response matches the Basket schema',
  await validationIssues(() =>
    createBasket({ return_url: 'https://example.com/cancel', complete_url: 'https://example.com/complete' }, { headers }),
  ),
);

const paid = (await tebex('GET', `/baskets/${paidBasketIdent}`)).json;
const { txnId, status, amount, currency } = paid.payment;
const { name, taxAmount, taxableAmount } = paid.priceDetails.tax;
finding(
  'Reading a paid basket fails validation',
  "payment is a Payment (transaction_id, status.id, price.amount) and priceDetails.tax is a number",
  [
    ...(await validationIssues(() => getBasketById(paidBasketIdent, { headers }))),
    `payment returned: ${JSON.stringify({ txnId, status, amount, currency })}`,
    `priceDetails.tax returned: ${JSON.stringify({ name, taxAmount, taxableAmount })}`,
  ],
);

const locked = await tebex('POST', '/baskets', {
  return_url: 'https://example.com/cancel',
  complete_url: 'https://example.com/complete',
  email: 'buyer@example.com',
  email_immutable: true,
});
finding(
  'email_immutable works, but isn\'t documented',
  'POST /baskets documents email_immutable',
  `sent "email_immutable": true, the basket came back with "email_immutable": ${locked.json.email_immutable}`,
);

const basket = await newBasket();
const invalidPackage = await tebex('POST', `/baskets/${basket.ident}/packages`, {
  package: { name: 'No price or type' },
  qty: 1,
});
finding(
  'A package without a price or type is a server error',
  '400 with field_details, like other invalid requests',
  `${invalidPackage.status} ${invalidPackage.text}`,
);

const invalidSale = await tebex('POST', `/baskets/${basket.ident}/sales`, { name: 'Sale', amount: 10 });
const unknownBasket = await tebex('GET', '/baskets/does-not-exist');
const refund = refundedTransactionId
  ? await tebex('POST', `/payments/${refundedTransactionId}/refund?type=txn_id`)
  : null;
finding(
  'Errors come in different shapes, and the spec describes none of them',
  'one error format, used by every error response in the spec',
  [
    `invalid sale: ${invalidSale.status} ${invalidSale.text}`,
    `unknown basket: ${unknownBasket.status} ${unknownBasket.text}`,
    ...(refund ? [`refunding a refunded payment: ${refund.status} ${refund.text}`] : []),
  ],
);
